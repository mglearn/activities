/* build-translations.mjs — assemble per-activity translation overlays into
   assets/i18n-activities-tr.js (window.EM_TR). Each translation source file
   (data/translations/<id>.json) is an array of {en,es,vi,ar,zh,ur,hi}; the
   overlay is keyed by the exact English source string so the activity page's
   t()-passthrough resolves it. Also reports coverage: which student-facing
   source strings still fall back to English.
   Run: node scripts/build-translations.mjs */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LANGS = ['es', 'vi', 'ar', 'zh', 'ur', 'hi'];

// Re-derive the student-facing source strings for an activity (mirrors extract-i18n.mjs).
const fieldsJs = readFileSync(join(root, 'assets', 'i18n-fields.js'), 'utf8');
const fsb = {}; new Function('window', fieldsJs).call(null, fsb);
const LABEL_KEYS = new Set(Object.keys(fsb.EM_FIELDS.en));
const isContent = (s) => typeof s === 'string' && s.trim() && !LABEL_KEYS.has(s);
function sourceStrings(a) {
  const out = []; const push = s => { if (isContent(s) && !out.includes(s)) out.push(s); };
  push(a.title); push(a.summary); push(a.challenge);
  if (a.event) { push(a.event.title); push(a.event.place); }
  (a.comparePromptKeys || []).forEach(push); push(a.conclusionKey);
  if (a.ace) { push(a.ace.articulateKey); push(a.ace.connectKey); push(a.ace.extendKey); }
  (a.sources || []).forEach(s => { push(s.titleKey); push(s.descKey); (s.questionKeys || []).forEach(push); });
  (a.stakeholders || []).forEach(sh => { push(sh.nameKey); if (sh.teacher) Object.values(sh.teacher).forEach(push); });
  (function walk(v, k) {
    if (typeof v === 'string') { if (k !== 'labelKey') push(v); }
    else if (Array.isArray(v)) v.forEach(x => walk(x, k));
    else if (v && typeof v === 'object') for (const [kk, val] of Object.entries(v)) walk(val, kk);
  })(a.mapData, null);
  return out;
}

const trDir = join(root, 'data', 'translations');
if (!existsSync(trDir)) { console.error('No data/translations/ dir. Nothing to build.'); process.exit(0); }

const EM_TR = {};
const actDir = join(root, 'data', 'activities');
const activities = {};
for (const f of readdirSync(actDir).filter(f => f.endsWith('.json'))) {
  const a = JSON.parse(readFileSync(join(actDir, f), 'utf8')); activities[a.id] = a;
}

let totalMissing = 0;
for (const f of readdirSync(trDir).filter(f => f.endsWith('.json'))) {
  const id = f.replace(/\.json$/, '');
  const rows = JSON.parse(readFileSync(join(trDir, f), 'utf8'));
  const byEn = new Map(rows.map(r => [r.en, r]));
  const overlay = {}; LANGS.forEach(l => overlay[l] = {});
  for (const r of rows) for (const l of LANGS) if (r[l]) overlay[l][r.en] = r[l];
  EM_TR[id] = overlay;

  // Boston Tea Party is localized via its own dictionary (i18n-voices-btp.js);
  // its overlay only carries hub title/summary, so skip the coverage report.
  if (id === 'boston-tea-party') { console.log(`  ${id}: hub title/summary overlay (page uses EM_ACT_BTP)`); continue; }
  // Coverage against the activity's actual source strings
  const src = activities[id] ? sourceStrings(activities[id]) : [];
  const missing = src.filter(s => !byEn.has(s));
  if (missing.length) { totalMissing += missing.length; console.warn(`  ${id}: ${missing.length}/${src.length} source strings NOT translated (fall back to en)`); }
  else console.log(`  ${id}: all ${src.length} source strings covered`);
}

const out = '/* GENERATED by scripts/build-translations.mjs — do not edit by hand.\n' +
  '   Source: data/translations/*.json. Machine-assisted, pending fluent-speaker review. */\n' +
  'window.EM_TR = ' + JSON.stringify(EM_TR) + ';\n';
writeFileSync(join(root, 'assets', 'i18n-activities-tr.js'), out);
console.log(`\nbuild-translations: wrote assets/i18n-activities-tr.js for ${Object.keys(EM_TR).length} activities` +
  (totalMissing ? `; ${totalMissing} strings fall back to English` : '; full coverage'));
